// Our texts follow the language of the game's texts (language.cpp)
static const struct {
	const char *code;
	const char *const *texts;
} kLanguages[] = {
	{"en", kEnglish},
	{"es", kSpanish},
	{"fr", kFrench},
	{"de", kGerman},
	{"it", kItalian},
	{"pt", kPortuguese},
};

static const char *const *OurTexts(void)
{
	const char *code = LanguageCode();
	for (int l = 0; l < (int)(sizeof kLanguages / sizeof kLanguages[0]); l++) {
		if (!strcmp(code, kLanguages[l].code)) {
			return kLanguages[l].texts;
		}
	}
	return kEnglish;
}

const char *Tr(TextId id)
{
	if (id < 0 || id >= TXT_COUNT) {
		return "";
	}
	const char *text = OurTexts()[id];
	return text ? text : kEnglish[id];
}
